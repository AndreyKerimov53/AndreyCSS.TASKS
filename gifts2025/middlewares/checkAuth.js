module.exports = function(req, res, next) {
    // Проверяем, есть ли user_id в сессии
    if (!req.session.user_id) {
        // Если пользователь НЕ авторизован - редирект на главную
        console.log('Пользователь не авторизован, доступ запрещен');
        res.redirect("/");
    } else {
        // Если пользователь авторизован - продолжаем
        console.log('Пользователь авторизован, доступ разрешен');
        next();
    }
};